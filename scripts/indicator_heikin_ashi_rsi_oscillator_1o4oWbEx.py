from pynecore.lib import (
    close, color, fill, format, high, hline, input, low, math, na, nz, ohlc4,
    plot, plotcandle, script, ta
)
from pynecore.types import Color, PersistentSeries, Series

TT_HARSI: str = 'Period for the RSI calculations used to generate the' + 'candles. This seperate from the RSI plot/histogram length.'
TT_PBIAS: str = 'Smoothing feature for the OPEN of the HARSI candles.' + '\n\nIncreases bias toward the prior open value which can' + ' help provide better visualisation of trend strength.' + '\n\n** By changing the Open values, High and Low can also' + ' be distorted - however Close will remain unchanged.'
TT_SMRSI: str = 'This option smoothes the RSI in a manner similar to HA' + ' open, but uses the realtime rsi rather than the prior' + ' close value.'
TT_STOCH: str = 'Uses the RSI generated by the above settings, and as such' + ' will be affected by the smoothing option.'
TT_STFIT: str = 'Adjusts the vertical scaling of the stochastic, can help' + ' to prevent distortion of other data in the channel.' + '\n\nHas no impact cross conditions.'
GROUP_CAND: str = 'Config » HARSI Candles'
INLINE_COL: str = 'Colour Pallette'
GROUP_PLOT: str = 'Config » RSI Plot'
GROUP_STOCH: str = 'Config » Stochastic RSI Plot'
INLINE_STDS: str = 'Stoch Draw States'
GROUP_CHAN: str = 'Config » OB/OS Boundaries'


@script.indicator('Heikin Ashi RSI Oscillator', 'HARSI •', False, format.price, 2, na_bool=True)
def main(
    i_lenHARSI=input.int(14, 'Length', group=GROUP_CAND, minval=1, tooltip=TT_HARSI),
    i_smoothing=input.int(1, 'Open Smoothing', group=GROUP_CAND, minval=1, maxval=100, tooltip=TT_PBIAS),
    i_colUp=input.color(color.teal, 'Colour Pallette  ', group=GROUP_CAND, inline=INLINE_COL),
    i_colDown=input.color(color.red, ' ', group=GROUP_CAND, inline=INLINE_COL),
    i_colWick=input.color(color.gray, ' ', group=GROUP_CAND, inline=INLINE_COL),
    i_source: Series[float] = input.source(ohlc4, 'Source', group=GROUP_PLOT),
    i_lenRSI=input.int(7, 'Length', group=GROUP_PLOT, minval=1),
    i_mode=input.bool(True, 'Smoothed Mode RSI?', group=GROUP_PLOT, tooltip=TT_SMRSI),
    i_showPlot=input.bool(True, 'Show RSI Plot?', group=GROUP_PLOT),
    i_showHist=input.bool(True, 'Show RSI Histogram?', group=GROUP_PLOT),
    i_showStoch=input.bool(False, 'Show Stochastic? ', group=GROUP_STOCH, inline=INLINE_STDS, tooltip=TT_STOCH),
    i_ribbon=input.bool(True, 'Ribbon?', group=GROUP_STOCH, inline=INLINE_STDS),
    i_smoothK=input.int(3, 'Smoothing K', group=GROUP_STOCH, minval=1),
    i_smoothD=input.int(3, 'Smoothing D', group=GROUP_STOCH, minval=1),
    i_stochLen=input.int(14, 'Stochastic Length', group=GROUP_STOCH, minval=1),
    i_stochFit=input.int(80, 'Stoch Scaling %', group=GROUP_STOCH, minval=1, maxval=100, tooltip=TT_STFIT),
    i_upper=input.int(20, 'OB', group=GROUP_CHAN, inline='OB', minval=1, maxval=50),
    i_upperx=input.int(30, 'OB Extreme', group=GROUP_CHAN, inline='OB', minval=1, maxval=50),
    i_lower=input.int(-20, 'OS', group=GROUP_CHAN, inline='OS', minval=-50, maxval=-1),
    i_lowerx=input.int(-30, 'OS Extreme', group=GROUP_CHAN, inline='OS', minval=-50, maxval=-1)
):
    def f_zrsi(_source, _length):
        return ta.rsi(_source, _length) - 50

    def f_zstoch(_source, _length, _smooth, _scale):
        _zstoch: float = ta.stoch(_source, _source, _source, _length) - 50
        _smoothed: float = ta.sma(_zstoch, _smooth)
        _scaled: float = _smoothed / 100 * _scale
        return _scaled

    def f_rsi(_source, _length, _mode):
        _zrsi: float = f_zrsi(_source, _length)
        _smoothed: PersistentSeries[float] = na(float)
        _smoothed = _zrsi if na(_smoothed[1]) else (_smoothed[1] + _zrsi) / 2
        return _smoothed if _mode else _zrsi

    def f_rsiHeikinAshi(_length):
        _closeRSI: Series[float] = f_zrsi(close, _length)
        _openRSI: float = nz(_closeRSI[1], _closeRSI)
        _highRSI_raw: float = f_zrsi(high, _length)
        _lowRSI_raw: float = f_zrsi(low, _length)
        _highRSI: float = math.max(_highRSI_raw, _lowRSI_raw)
        _lowRSI: float = math.min(_highRSI_raw, _lowRSI_raw)
        _close: Series[float] = (_openRSI + _highRSI + _lowRSI + _closeRSI) / 4
        _open: PersistentSeries[float] = na(float)
        _open = (_openRSI + _closeRSI) / 2 if na(_open[i_smoothing]) else (_open[1] * i_smoothing + _close[1]) / (i_smoothing + 1)
        _high: float = math.max(_highRSI, math.max(_open, _close))
        _low: float = math.min(_lowRSI, math.min(_open, _close))
        return (_open, _high, _low, _close)

    RSI: float = f_rsi(i_source, i_lenRSI, i_mode)
    StochK: float = f_zstoch(RSI, i_stochLen, i_smoothK, i_stochFit)
    StochD: float = ta.sma(StochK, i_smoothD)
    O, H, L, C = f_rsiHeikinAshi(i_lenHARSI)
    bodyColour: Color = i_colUp if C > O else i_colDown
    wickColour: Color = i_colWick
    colShadow: Color = color.rgb(0, 0, 0, 20)
    colNone: Color = color.rgb(0, 0, 0, 100)
    colRSI: Color = color.rgb(250, 200, 50, 0)
    colStochK: Color = color.new(color.new('#0094FF'), 0)
    colStochD: Color = color.new(color.new('#FF6A00'), 0)
    colStochFill: Color = color.new(colStochK, 50) if StochK >= StochD else color.new(colStochD, 50)
    upperx = hline(i_upperx, 'OB Extreme', color.new(color.silver, 60))
    upper = hline(i_upper, 'OB', color.new(color.silver, 80))
    median = hline(0, 'Median', color.orange, hline.style_dotted)
    lower = hline(i_lower, 'OS', color.new(color.silver, 80))
    lowerx = hline(i_lowerx, 'OS Extreme', color.new(color.silver, 60))
    fill(upper, upperx, color.new(color.red, 90), title='Background Fill OB')
    fill(upper, lower, color.new(color.blue, 90), title='Background Channel')
    fill(lower, lowerx, color.new(color.green, 90), title='Background Fill OS')
    plot(RSI if i_showHist else na, 'RSI Histogram', color.new(color.silver, 80), 1, plot.style_histogram)
    plotcandle(O, H, L, C, 'HARSI', bodyColour, wickColour, bordercolor=bodyColour)
    plot(RSI if i_showPlot else na, 'RSI Shadow', colShadow, 3)
    plot_rsi = plot(RSI if i_showPlot else na, 'RSI Overlay', colRSI, 1)
    plot(StochK if i_showStoch else na, 'Stoch K Shadow', colShadow if not i_ribbon else colNone, 3)
    plot(StochD if i_showStoch else na, 'Stoch D Shadow', colShadow if not i_ribbon else colNone, 3)
    plot_stochK = plot(StochK if i_showStoch else na, 'Stoch K', colStochK if not i_ribbon else colNone, 1)
    plot_stochD = plot(StochD if i_showStoch else na, 'Stoch D', colStochD if not i_ribbon else colNone, 1)
    fill(plot_stochK, plot_stochD, colStochFill if i_ribbon else na)


if __name__ == "__main__":
    from pynecore.standalone import run
    run(__file__)
